"""Печать сумм в рублях и заголовков отчёта."""


def format_kopeks(kopeks: int) -> str:
    """Переводит сумму из копеек в строку рублей.

    Args:
        kopeks: Сумма в копейках, целое число.

    Returns:
        Строка вида «1 250,00 ₽»: пробел между разрядами, запятая перед копейками.
    """
    return f"{kopeks / 100:,.2f} ₽".replace(",", " ").replace(".", ",")


def format_title(text: str, width: int = 40) -> str:
    """Ставит заголовок по центру строки и заполняет края знаками равенства.

    Args:
        text: Текст заголовка.
        width: Ширина строки в символах. По умолчанию 40.

    Returns:
        Строка заголовка заданной ширины.
    """
    return text.center(width, "=")
